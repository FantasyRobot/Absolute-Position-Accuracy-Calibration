% syms q1 q2 q3 q4 q5 q6;
% syms d0 d1 d2 d3 d4 d5 a1 a3;
% syms o_1x o_1y o_1z;
% syms o_2x o_2y o_2z;
% syms o_3x o_3y o_3z;
% syms o_4x o_4y o_4z;
% syms o_5x o_5y o_5z;
% syms o_6x o_6y o_6z;

function [P, R] = T12Model(q1,q2,q3,q4,q5,q6,...
                           d0, d1, d2, d3, d4, d5, a1, a3,...
                           o_1x, o_1y, o_1z, o_2x, o_2y, o_2z, o_3x, o_3y, o_3z, ...
                           o_4x, o_4y, o_4z, o_5x, o_5y, o_5z, o_6x, o_6y, o_6z ...
                            )
     
    %2\3\5÷·∑¥œÚ
%     s1=sin(q1);c1=cos(q1);
%     s2=sin(-q2);c2=cos(-q2);
%     s3=sin(-q3);c3=cos(-q3);
%     s4=sin(q4);c4=cos(q4);
%     s5=sin(-q5);c5=cos(-q5);
%     s6=sin(q6);c6=cos(q6);
    s1=sin(q1);c1=cos(q1);
    s2=sin(q2);c2=cos(q2);
    s3=sin(q3);c3=cos(q3);
    s4=sin(q4);c4=cos(q4);
    s5=sin(q5);c5=cos(q5);
    s6=sin(q6);c6=cos(q6);

    R01=[c1, -s1,0;...
         s1,c1,0;...
         0,0,1];
    R12=[c2, 0, s2;...
        0,1,0;...
        -s2,0,c2];
    R23=[c3, 0, s3;...
         0,1,0;...
         -s3,0,c3];
    R34=[1, 0, 0;...
         0,c4,-s4;...
         0,s4,c4];
    R45=[c5, 0, s5;...
         0,1,0;...
         -s5,0,c5];
    R56=[1, 0, 0;...
         0,c6,-s6;...
         0,s6,c6];
    RT =[1,0,0;...
        -0,0,1;...
        0,-1,0];
    R=R01*R12*R23*R34*R45*R56*RT;
    P=[o_1x;o_1y;o_1z+d0] ...
        +R01*[o_2x+a1;o_2y;o_2z+d1] ...
        +(R01*R12)*[o_3x;o_3y;o_3z+d2] ...
        +(R01*R12*R23)*[o_4x+d3;o_4y;o_4z+a3]...
        +(R01*R12*R23*R34)*[o_5x+d4;o_5y;o_5z]...
        +(R01*R12*R23*R34*R45)*[o_6x;o_6y;o_6z]...
        +(R01*R12*R23*R34*R45*R56)*[d5;0;0];
end
